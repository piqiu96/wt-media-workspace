const {chromium}=require('playwright');
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'chrome'});const page=await browser.newPage({viewport:{width:1600,height:1000}});
 const root=process.cwd(),url='file://'+root+'/example/common/index.html',out=path.join(root,'delivery/active/CHG-20261028-099/evidence/frontend-controls');fs.mkdirSync(out,{recursive:true});
 const checks=[],errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
 const ok=(n,b)=>{assert.ok(b,n);checks.push(n)};
 await page.goto(url+'#list');
 const trigger=page.locator('#list-mode-trigger');await trigger.click();
 ok('选择器打开统一选项面板',await page.locator('#list-mode-options').evaluate(e=>e.matches(':popover-open')));
 await page.keyboard.press('ArrowDown');await page.keyboard.press('Enter');
 ok('键盘选择回写真实值',await page.locator('#list-mode').inputValue()==='系统托管');
 ok('关闭后保留触发器焦点',await trigger.evaluate(e=>e===document.activeElement));
 await trigger.click();await page.keyboard.press('Escape');
 ok('Esc只关闭选择面板',await trigger.getAttribute('aria-expanded')==='false');
 await trigger.click();await page.getByRole('heading',{name:'浏览器窗口',exact:true}).click();
 ok('点击外部关闭面板',await trigger.getAttribute('aria-expanded')==='false');
 await trigger.click();await page.screenshot({path:path.join(out,'select-list-1600.png')});await page.keyboard.press('Escape');
 await page.locator('#list-mode').evaluate(e=>{e.options[2].disabled=true;});
 await trigger.click();await page.locator('#list-mode-option-2').click({force:true});
 ok('禁用选项不可写入',await page.locator('#list-mode').inputValue()==='系统托管');await page.keyboard.press('Escape');
 await page.locator('#list-mode').evaluate(e=>{e.disabled=true;});
 ok('源控件禁用同步触发器',await trigger.isDisabled());
 await page.locator('#list-mode').evaluate(e=>{e.disabled=false;e.options[2].disabled=false;});
 await trigger.click();await page.keyboard.press('Home');await page.keyboard.press('Enter');
 ok('Home键可回到首项',await page.locator('#list-mode').inputValue()==='');

 const color=await page.locator('[data-resource-row]').first().getByRole('button',{name:'编辑',exact:true}).evaluate(e=>getComputedStyle(e).color);
 ok('次要行操作中性色',color==='rgb(101, 113, 132)');
 await page.goto(url+'#foundations');await page.locator('[data-menu-trigger]').click();
 ok('更多打开浮动菜单',await page.locator('[data-menu-popup]').evaluate(e=>e.matches(':popover-open')));
 await page.keyboard.press('ArrowDown');ok('菜单键盘可达危险操作',await page.getByRole('menuitem',{name:'停用',exact:true}).evaluate(e=>e===document.activeElement));
 await page.screenshot({path:path.join(out,'more-menu-1600.png')});await page.keyboard.press('Escape');
 ok('菜单Esc恢复触发器',await page.locator('[data-menu-trigger]').evaluate(e=>e===document.activeElement));
 await page.locator('[data-menu-trigger]').click();await page.getByRole('menuitem',{name:'停用',exact:true}).click();
 ok('菜单动作可打开确认',await page.locator('dialog[open]').count()===1);await page.locator('dialog .ex-close').click();
 await page.goto(url+'#feedback');await page.getByRole('button',{name:'查看关联账号',exact:true}).click();
 ok('关联账号就地展开无新弹层',await page.locator('#impact-accounts').isVisible() && await page.locator('dialog[open]').count()===0);
 await page.goto(url+'#overlays');await page.getByRole('button',{name:'可用与不可用资源'}).click();
 let dialog=page.locator('dialog[open]');
 const positions=await dialog.locator('[data-picker-search] .ex-field').evaluateAll(a=>a.map(e=>{let r=e.getBoundingClientRect();return{x:r.x,y:r.y,w:r.width}}));
 ok('选择器筛选同排对齐',Math.abs(positions[0].y-positions[1].y)<1);
 ok('筛选横向间隔24px',Math.abs(positions[1].x-positions[0].x-positions[0].w-24)<1);
 await dialog.locator('#picker-region-trigger').click();await page.keyboard.press('ArrowDown');await page.keyboard.press('Enter');
 ok('弹层选择器真实触发筛选',await dialog.locator('#picker-region').inputValue()==='上海');
 ok('选择面板高于Dialog且保持当前层',await page.locator('dialog[open]').count()===1);
 await dialog.getByRole('button',{name:'详情',exact:true}).click();
 ok('少量代理详情当前区域展开',await dialog.locator('[data-proxy-preview]').isVisible() && await page.locator('dialog[open]').count()===1);
 await dialog.getByRole('button',{name:'查看账号',exact:true}).click();
 await page.screenshot({path:path.join(out,'picker-inline-1600.png')});
 await dialog.getByRole('button',{name:'查看完整代理详情'}).click();
 ok('完整详情才进入下一层',await page.locator('dialog[open]').count()===2);
 await page.locator('dialog[open]').last().locator('.ex-close').click();
 ok('返回保留地区筛选',await page.locator('#picker-region').inputValue()==='上海');
 await page.locator('dialog[open]').last().locator('.ex-close').click();
 for(const viewport of [{width:1366,height:900},{width:390,height:844}]){
  await page.setViewportSize(viewport);await page.goto(url+'#overlays');await page.getByRole('button',{name:'可用与不可用资源'}).click();dialog=page.locator('dialog[open]');
  const d=await dialog.locator('[data-picker-search] .ex-field').evaluateAll(a=>a.map(e=>{let r=e.getBoundingClientRect();return{x:r.x,y:r.y,w:r.width,h:r.height}}));
  if(viewport.width===390)ok('窄屏筛选整组换行且间隔20px',d[1].y-d[0].y-d[0].h>=19);
  else ok('1366宽视口筛选同排',Math.abs(d[1].y-d[0].y)<1);
  await dialog.locator('#picker-region-trigger').click();
  const b=await dialog.locator('#picker-region-options').boundingBox();
  ok(viewport.width+'-选项面板不超出视口',b.x>=0&&b.y>=0&&b.x+b.width<=viewport.width+1&&b.y+b.height<=viewport.height+1);
  await page.keyboard.press('Escape');ok(viewport.width+'-面板Esc不关闭Dialog',await page.locator('dialog[open]').count()===1);
  if(viewport.width===390)await page.screenshot({path:path.join(out,'picker-390.png')});
  await dialog.locator('.ex-close').click();
 }
 ok('无脚本错误',errors.length===0);
 fs.writeFileSync(path.join(out,'results.json'),JSON.stringify({checks:checks.length,results:checks,errors,checkedAt:new Date().toISOString()},null,2)+'\n');
 console.log(JSON.stringify({checks:checks.length,errors},null,2));await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
